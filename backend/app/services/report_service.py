def sanitize_csv_cell(val: Any) -> Any:
    """Protect against spreadsheet formula injection (=, +, -, @)."""
    if val is None:
        return ""
    s = str(val)
    if s and s[0] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + s
    return s


