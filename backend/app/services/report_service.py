    # ─────────────────────────────────────────────────────────────────────────
    # Compile Report Data
    # ─────────────────────────────────────────────────────────────────────────
    @staticmethod
    def _compile_data(report_type: ReportType, filters: ReportFilterOptions, db: Session) -> Dict[str, Any]:
        filters = filters or ReportFilterOptions()
        limit = min(filters.limit or 1000, 5000)
        now_str = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

        data: Dict[str, Any] = {
            "report_type": report_type.value,
            "generated_at": now_str,
            "applied_filters": filters.model_dump(exclude_none=True),
            "limitations": SCIENTIFIC_CAVEATS,
        }

        if report_type == ReportType.CONSERVATION_OVERVIEW:
            data["title"] = "National Wildlife Conservation Overview Report"
            sp_query = db.query(Species)
            if filters.taxonomic_class:
                sp_query = sp_query.filter(Species.class_name == filters.taxonomic_class)
            if filters.iucn_category:
                sp_query = sp_query.filter(Species.iucn_category == filters.iucn_category)

            species_list = sp_query.order_by(Species.common_name).limit(limit).all()
            total_sp = sp_query.count()
            total_obs = db.query(Observation).count()

            # Distributions
            taxa_dist = db.query(Species.class_name, func.count(Species.id)).group_by(Species.class_name).all()
            iucn_dist = db.query(Species.iucn_category, func.count(Species.id)).group_by(Species.iucn_category).all()
            source_dist = db.query(DataSource.name, func.count(Observation.id))\
                .join(Observation, DataSource.id == Observation.source_id)\
                .group_by(DataSource.name).all()

            data["summary"] = {
                "Total Verified Species": total_sp,
                "Total Occurrence Records": total_obs,
                "Target Query Species Sample": len(species_list),
            }
            data["taxa_distribution"] = [{"class": c or "Unspecified", "count": cnt} for c, cnt in taxa_dist]
            data["iucn_distribution"] = [{"status": s or "DD", "count": cnt} for s, cnt in iucn_dist]
            data["source_distribution"] = [{"source": src or "Unknown", "count": cnt} for src, cnt in source_dist]
            data["table_headers"] = ["ID", "Common Name", "Scientific Name", "Class", "IUCN Category"]
            data["table_rows"] = [
                [sp.id, sp.common_name, sp.scientific_name, sp.class_name or "N/A", sp.iucn_category]
                for sp in species_list
            ]

        elif report_type == ReportType.SPECIES_CONSERVATION:
            species_id = filters.species_id
            target_species = None
            if species_id:
                target_species = db.query(Species).filter(Species.id == species_id).first()
            if not target_species:
                target_species = db.query(Species).first()
                species_id = target_species.id if target_species else None

            data["title"] = f"Species Conservation Dossier: {target_species.common_name if target_species else 'Unknown'}"
            obs_query = db.query(Observation).filter(Observation.species_id == species_id)\
                .order_by(Observation.observed_at.desc())
            total_obs = obs_query.count()
            obs_list = obs_query.limit(limit).all()

            risk_rec = db.query(MLRiskScore).filter(MLRiskScore.species_id == species_id).first()

            data["summary"] = {
                "Common Name": target_species.common_name if target_species else "N/A",
                "Scientific Name": target_species.scientific_name if target_species else "N/A",
                "Taxonomic Order": target_species.order_name or "N/A",
                "Family": target_species.family or "N/A",
                "IUCN Red List Status": target_species.iucn_category or "N/A",
                "Verified Observations": total_obs,
                "Platform ML Risk Level": risk_rec.risk_level if risk_rec else "NOT ASSESSED",
                "Extinction Risk Score": f"{risk_rec.risk_score:.3f}" if risk_rec and risk_rec.risk_score else "N/A",
            }
            data["table_headers"] = ["Obs ID", "Date", "Latitude", "Longitude", "Source", "Status"]
            data["table_rows"] = [
                [
                    o.id,
                    o.observed_at.strftime("%Y-%m-%d %H:%M") if o.observed_at else "N/A",
                    f"{o.latitude:.4f}",
                    f"{o.longitude:.4f}",
                    o.source.name if o.source else "Unknown",
                    o.verification_status,
                ]
                for o in obs_list
            ]

        elif report_type == ReportType.GEOGRAPHIC_INTELLIGENCE:
            loc = None
            if filters.location_id:
                loc = db.query(Location).filter(Location.id == filters.location_id).first()
            if not loc:
                loc = db.query(Location).first()

            loc_id = loc.id if loc else None
            data["title"] = f"Geographic Intelligence Report: {loc.name if loc else 'National Territory'}"

            obs_query = db.query(Observation)
            if loc_id:
                obs_query = obs_query.filter(Observation.location_id == loc_id)
            total_obs = obs_query.count()
            obs_list = obs_query.order_by(Observation.observed_at.desc()).limit(limit).all()

            data["summary"] = {
                "Protected Area": loc.name if loc else "Pan-India",
                "State": loc.state if loc else "Various",
                "Designation": loc.protected_area_type if loc else "Multiple",
                "Habitat": loc.protected_area_type if loc else "Mixed Ecosystems",
                "Total Observations": total_obs,
            }
            data["table_headers"] = ["Obs ID", "Species", "Observed Date", "Latitude", "Longitude", "Source"]
            data["table_rows"] = [
                [
                    o.id,
                    o.species.common_name if o.species else "Unknown",
                    o.observed_at.strftime("%Y-%m-%d") if o.observed_at else "N/A",
                    f"{o.latitude:.4f}",
                    f"{o.longitude:.4f}",
                    o.source.name if o.source else "Unknown",
                ]
                for o in obs_list
            ]

        elif report_type == ReportType.THREAT_RISK_ASSESSMENT:
            data["title"] = "Anthropogenic Threat & Extinction Risk Assessment Report"
            threat_rows = db.query(
                Threat.category_name,
                Threat.severity_weight,
                func.count(DocumentThreat.threat_id).label("incidents")
            ).join(DocumentThreat, Threat.id == DocumentThreat.threat_id)\
             .group_by(Threat.category_name, Threat.severity_weight)\
             .order_by(func.count(DocumentThreat.threat_id).desc()).all()

            ml_rows = db.query(
                Species.common_name,
                Species.scientific_name,
                Species.iucn_category,
                MLRiskScore.risk_level,
                MLRiskScore.risk_score
            ).join(Species, MLRiskScore.species_id == Species.id)\
             .order_by(MLRiskScore.risk_score.desc()).limit(limit).all()

            data["summary"] = {
                "Active Threat Categories": len(threat_rows),
                "Documented Incident Mentions": sum(r.incidents for r in threat_rows),
                "Species Assessed by ML": len(ml_rows),
            }
            data["threat_breakdown"] = [
                {"category": r.category_name, "severity": r.severity_weight, "incidents": r.incidents}
                for r in threat_rows
            ]
            data["table_headers"] = ["Common Name", "Scientific Name", "IUCN Status", "ML Risk Level", "Risk Score"]
            data["table_rows"] = [
                [r.common_name, r.scientific_name, r.iucn_category, r.risk_level, f"{r.risk_score:.3f}" if r.risk_score else "N/A"]
                for r in ml_rows
            ]

        elif report_type == ReportType.RESEARCH_DOCUMENT_INTELLIGENCE:
            data["title"] = "Research & Document Intelligence Digest"
            docs = db.query(Document).order_by(Document.published_date.desc()).limit(limit).all()

            data["summary"] = {
                "Total Documents Indexed": len(docs),
            }
            data["table_headers"] = ["Doc ID", "Title", "Source", "Published Date", "File Type"]
            data["table_rows"] = [
                [
                    d.id,
                    d.title,
                    d.source_name or "N/A",
                    d.published_date.strftime("%Y-%m-%d") if d.published_date else "N/A",
                    d.file_type or "PDF",
                ]
                for d in docs
            ]

        return data

    # ─────────────────────────────────────────────────────────────────────────
    # Format Generators: CSV, XLSX, PDF
    # ─────────────────────────────────────────────────────────────────────────
    @classmethod
    def generate_csv(cls, report_type: ReportType, filters: ReportFilterOptions, db: Session) -> Tuple[bytes, str]:
        data = cls._compile_data(report_type, filters, db)
        output = io.StringIO()
        writer = csv.writer(output)

        # Institutional Header
        writer.writerow(["WILDLIFE CONSERVATION INTELLIGENCE PLATFORM"])
        writer.writerow([data["title"].upper()])
        writer.writerow(["Generated At", data["generated_at"]])
        writer.writerow([])

        # Summary Block
        writer.writerow(["--- EXECUTIVE SUMMARY ---"])
        for k, v in data.get("summary", {}).items():
            writer.writerow([k, sanitize_csv_cell(v)])
        writer.writerow([])

        # Main Table
        writer.writerow(["--- TABULAR DATA ---"])
        writer.writerow(data.get("table_headers", []))
        for row in data.get("table_rows", []):
            writer.writerow([sanitize_csv_cell(cell) for cell in row])
        writer.writerow([])

        # Scientific Limitations
        writer.writerow(["--- METHODOLOGICAL LIMITATIONS & CAVEATS ---"])
        for cav in data.get("limitations", []):
            writer.writerow([sanitize_csv_cell(cav)])

        filename = f"{report_type.value.lower()}_{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}.csv"
        return output.getvalue().encode("utf-8"), filename

    @classmethod
    def generate_xlsx(cls, report_type: ReportType, filters: ReportFilterOptions, db: Session) -> Tuple[bytes, str]:
        data = cls._compile_data(report_type, filters, db)
        wb = openpyxl.Workbook()

        # Styles
        primary_font = Font(name="Segoe UI", size=11)
        title_font = Font(name="Segoe UI", size=14, bold=True, color="FFFFFF")
        section_font = Font(name="Segoe UI", size=12, bold=True, color="11682F")
        header_font = Font(name="Segoe UI", size=11, bold=True, color="FFFFFF")
        bold_font = Font(name="Segoe UI", size=11, bold=True)

        header_fill = PatternFill(start_color="11682F", end_color="11682F", fill_type="solid")
        title_fill = PatternFill(start_color="0F0E0C", end_color="0F0E0C", fill_type="solid")
        zebra_fill = PatternFill(start_color="F5F1EA", end_color="F5F1EA", fill_type="solid")
        border_thin = Border(
            left=Side(style="thin", color="DDDDDD"),
            right=Side(style="thin", color="DDDDDD"),
            top=Side(style="thin", color="DDDDDD"),
            bottom=Side(style="thin", color="DDDDDD")
        )

        # ── Sheet 1: Summary & Metrics
        ws_sum = wb.active
        ws_sum.title = "Executive Summary"
        ws_sum.views.sheetView[0].showGridLines = True

        ws_sum.merge_cells("A1:D1")
        cell_a1 = ws_sum["A1"]
        cell_a1.value = "WILDLIFE CONSERVATION INTELLIGENCE PLATFORM"
        cell_a1.font = title_font
        cell_a1.fill = title_fill
        cell_a1.alignment = Alignment(horizontal="center", vertical="center")
        ws_sum.row_dimensions[1].height = 30

        ws_sum["A3"] = "Report Title:"
        ws_sum["B3"] = data["title"]
        ws_sum["A4"] = "Generated At:"
        ws_sum["B4"] = data["generated_at"]
        ws_sum["A3"].font = bold_font
        ws_sum["A4"].font = bold_font

        ws_sum["A6"] = "METRICS & AGGREGATIONS"
        ws_sum["A6"].font = section_font
        row_idx = 7
        for k, v in data.get("summary", {}).items():
            ws_sum.cell(row=row_idx, column=1, value=k).font = bold_font
            ws_sum.cell(row=row_idx, column=2, value=str(v)).font = primary_font
            row_idx += 1

        row_idx += 2
        ws_sum.cell(row=row_idx, column=1, value="SCIENTIFIC LIMITATIONS & INTERPRETATION CAVEATS").font = section_font
        row_idx += 1
        for cav in data.get("limitations", []):
            ws_sum.cell(row=row_idx, column=1, value=f"• {cav}").font = primary_font
            row_idx += 1

        ws_sum.column_dimensions["A"].width = 35
        ws_sum.column_dimensions["B"].width = 50

        # ── Sheet 2: Tabular Data
        ws_data = wb.create_sheet(title="Report Data")
        ws_data.views.sheetView[0].showGridLines = True

        headers = data.get("table_headers", [])
        for col_idx, h in enumerate(headers, start=1):
            c = ws_data.cell(row=1, column=col_idx, value=h)
            c.font = header_font
            c.fill = header_fill
            c.alignment = Alignment(horizontal="center", vertical="center")
        ws_data.row_dimensions[1].height = 24

        rows = data.get("table_rows", [])
        for r_idx, r_val in enumerate(rows, start=2):
            for c_idx, val in enumerate(r_val, start=1):
                cell = ws_data.cell(row=r_idx, column=c_idx, value=val)
                cell.font = primary_font
                cell.border = border_thin
                if r_idx % 2 == 1:
                    cell.fill = zebra_fill

        # Auto column width
        for col in ws_data.columns:
            max_len = max(len(str(cell.value or "")) for cell in col)
            col_letter = openpyxl.utils.get_column_letter(col[0].column)
            ws_data.column_dimensions[col_letter].width = max(max_len + 3, 14)

        buf = io.BytesIO()
        wb.save(buf)
        filename = f"{report_type.value.lower()}_{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}.xlsx"
        return buf.getvalue(), filename

    @classmethod
    def generate_pdf(cls, report_type: ReportType, filters: ReportFilterOptions, db: Session) -> Tuple[bytes, str]:
        data = cls._compile_data(report_type, filters, db)
        buf = io.BytesIO()
        doc = SimpleDocTemplate(
            buf,
            pagesize=letter,
            rightMargin=40,
            leftMargin=40,
            topMargin=40,
            bottomMargin=40,
        )

        styles = getSampleStyleSheet()
        # Custom palette & typography
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=16,
            leading=20,
            textColor=colors.HexColor("#0F0E0C"),
        )
        subtitle_style = ParagraphStyle(
            "DocSubTitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#5E5B54"),
        )
        heading_style = ParagraphStyle(
            "DocHeading",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=12,
            leading=16,
            textColor=colors.HexColor("#11682F"),
            spaceBefore=14,
            spaceAfter=6,
        )
        body_style = ParagraphStyle(
            "DocBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=13,
            textColor=colors.HexColor("#2C2A26"),
        )
        caveat_style = ParagraphStyle(
            "DocCaveat",
            parent=styles["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=8,
            leading=11,
            textColor=colors.HexColor("#5E5B54"),
        )
        table_cell_style = ParagraphStyle(
            "TableCell",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8,
            leading=10,
            textColor=colors.HexColor("#1A1916"),
        )
        table_hdr_style = ParagraphStyle(
            "TableHdr",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=8,
            leading=10,
            textColor=colors.white,
        )

        story = []

        # ── Header Banner
        story.append(Paragraph("WILDLIFE CONSERVATION INTELLIGENCE PLATFORM", subtitle_style))
        story.append(Paragraph(data["title"], title_style))
        story.append(Spacer(1, 4))
        story.append(Paragraph(f"Generated at: {data['generated_at']} | Scope: Official & Verified Multi-Source Telemetry", subtitle_style))
        story.append(Spacer(1, 8))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#11682F"), spaceBefore=2, spaceAfter=10))

        # ── Executive Summary Metrics Table
        story.append(Paragraph("1. Executive Summary & Key Indicators", heading_style))
        summary_items = list(data.get("summary", {}).items())
        # Format as 2-column key-value grid
        summary_data = []
        for i in range(0, len(summary_items), 2):
            k1, v1 = summary_items[i]
            k2, v2 = summary_items[i + 1] if i + 1 < len(summary_items) else ("", "")
            summary_data.append([
                Paragraph(f"<b>{k1}:</b>", body_style),
                Paragraph(str(v1), body_style),
                Paragraph(f"<b>{k2}:</b>" if k2 else "", body_style),
                Paragraph(str(v2) if v2 else "", body_style),
            ])

        if summary_data:
            summary_table = Table(summary_data, colWidths=[120, 140, 120, 140])
            summary_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F9F8F5")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#DDD8CF")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#EFECE6")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            story.append(summary_table)

        story.append(Spacer(1, 12))

        # ── Tabular Sample Data
        story.append(Paragraph("2. Selected Registry Occurrence Records", heading_style))
        headers = data.get("table_headers", [])
        rows = data.get("table_rows", [])[:40]  # Limit to 40 items in PDF preview to keep presentation tidy

        pdf_table_data = [[Paragraph(h, table_hdr_style) for h in headers]]
        for r in rows:
            pdf_table_data.append([Paragraph(str(c), table_cell_style) for c in r])

        if headers and rows:
            # Dynamic column widths
            col_w = int(520 / len(headers))
            col_widths = [col_w] * len(headers)
            col_widths[1] = col_w + 30  # Give more width to Name/Species column
            col_widths[0] = col_w - 30

            pdf_table = Table(pdf_table_data, colWidths=col_widths, repeatRows=1)
            pdf_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#11682F")),
                ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E0D8")),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F5F1EA")]),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]))
            story.append(pdf_table)
            if len(data.get("table_rows", [])) > 40:
                story.append(Spacer(1, 4))
                story.append(Paragraph(f"<i>Displaying first 40 records of {len(data['table_rows'])} in PDF format. For the full dataset, export in CSV or XLSX format.</i>", caveat_style))

        story.append(Spacer(1, 14))

        # ── Caveats & Governance
        story.append(KeepTogether([
            Paragraph("3. Scientific Limitations & Data Governance", heading_style),
            HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#DDD8CF"), spaceBefore=2, spaceAfter=6),
            *[Paragraph(f"• {c}", caveat_style) for c in data.get("limitations", [])]
        ]))

        doc.build(story)
        filename = f"{report_type.value.lower()}_{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
        return buf.getvalue(), filename
